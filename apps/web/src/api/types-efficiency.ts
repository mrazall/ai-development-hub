export type Attribution = 'exact' | 'estimated' | 'unknown';
export type Observation = {
  code: string;
  severity: 'info' | 'notice';
  subject: Record<string, unknown>;
  params: Record<string, unknown>;
  criterion: string;
};
export type EfficiencyResponse = {
  filters: Record<string, unknown>;
  since: string | null;
  kpi: {
    completed_tasks: number;
    tokens_per_completed_task: number | null;
    cost_per_completed_task: number | null;
    cost_partial: boolean;
    median_wall_s: number | null;
    orchestrator_cost_share: number | null;
    orchestrator_cost_share_exact: boolean;
    confirmed_retries: number;
    total_tokens: number;
    total_cost_usd: number;
    unpriced_tokens: number;
  };
  series: {
    period: string;
    tokens: number;
    cost_usd: number;
    cost_partial: boolean;
    completed_tasks: number;
    cost_per_completed_task: number | null;
    tokens_per_completed_task: number | null;
  }[];
  granularity: 'day' | 'week';
  by_role: {
    role: 'orchestrator' | 'executor' | 'single';
    tokens: number;
    cost_usd: number;
    cost_partial: boolean;
    token_share: number;
    cost_share: number | null;
  }[];
  by_trigger: { trigger: Trigger; runs: number; tokens: number; cost_usd: number; cost_partial: boolean }[];
  context: {
    cache_read_share: number | null;
    fresh_to_cache_ratio: number | null;
    compactions: number | null;
    continuation_tokens: number;
  };
  observations: Observation[];
};
